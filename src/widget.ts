import { WebchatClient } from './client.js';
import type {
  WebchatClientOptions,
  WebchatMessage,
  WebchatSettings,
  WebchatSettingsOverrides,
  WebchatStatus,
} from './types.js';
import { WIDGET_CSS } from './widget-styles.js';

export interface WebchatWidgetOptions extends Omit<WebchatClientOptions, 'autoConnect'> {
  /**
   * Presentation overrides on top of what the agent serves from
   * GET /widget/config (the settings made in the Chat Studio).
   */
  settings?: WebchatSettingsOverrides;
  /** Skip fetching the Studio's settings; use only `settings` and the defaults. */
  fetchConfig?: boolean;
  /** Header title. Shortcut for `settings.agentName`. */
  title?: string;
  /** Line under the title. Defaults to the connection status. */
  subtitle?: string;
  /** First message shown in the panel. Shortcut for `settings.greetings`. */
  greeting?: string;
  /** Shortcut for `settings.inputPlaceholder`. */
  placeholder?: string;
  /** Shortcut for `settings.position`. Ignored when `target` is given. */
  position?: 'bottom-right' | 'bottom-left';
  /** Mount inside this element (selector or node) instead of floating. */
  target?: string | HTMLElement;
  /** Show the floating launcher button. Defaults to true unless `target` is set. */
  launcher?: boolean;
  /** Start with the panel open. Defaults to false unless `target` is set. */
  open?: boolean;
  /** Connect immediately, or wait until the panel is first opened (default). */
  connectOn?: 'load' | 'open';
  /** Shortcut for `settings.colors.launcher` + `settings.colors.userBubble`. */
  accent?: string;
  /** localStorage namespace; change it to keep two embeds of one agent apart. */
  storageKey?: string;
}

export interface WebchatWidget {
  /** The underlying client, for anything the widget does not expose. */
  readonly client: WebchatClient;
  /** The settings in effect (server config + overrides). */
  readonly settings: WebchatSettings;
  open(): void;
  close(): void;
  toggle(): void;
  /** Forgets the conversation and starts a new session. */
  newChat(): void;
  /** Removes the widget from the page and disconnects. */
  destroy(): void;
}

